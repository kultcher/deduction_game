#!/usr/bin/env python3
"""Regenerate tuning_catalogue.md: every constant in sim/tuning.gd, its value, its
comment and the files that use it.

Usage: python3 tools/tuning_index.py [--out tuning_catalogue.md]

Standard library only. Reads the repository; writes one markdown file. A constant counts
as used in a file when the file mentions `Tuning.<Class>.<NAME>`, or the bare name where
the file aliases it (many scripts keep `const NAME = Tuning.<Class>.NAME`).
"""
import argparse
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TUNING = os.path.join(ROOT, "sim", "tuning.gd")
CODE_DIRS = ["sim", "game", "workshop", "ui", "tools"]

INTRO = """# Tuning catalogue

Every constant in `sim/tuning.gd`, by class, with its value, the comment beside it and the
non-test files that use it. Generated by `python3 tools/tuning_index.py`; rerun it after
changing `sim/tuning.gd`. For what the numbers do together, read
[TUNING_NARRATIVE.md](TUNING_NARRATIVE.md).

"Used in" lists files that name the constant through `Tuning.<Class>.<NAME>` or through a
local alias of the same name. "(unused)" means no file outside `sim/tuning.gd` mentions
it: a retired value kept for compatibility, or a candidate for deletion.

"""


def parse_tuning(text):
    classes = []
    cur = None
    pending = []
    lines = text.split("\n")
    i = 0
    while i < len(lines):
        line = lines[i]
        m = re.match(r"^class (\w+):", line)
        if m:
            cur = {"name": m.group(1), "consts": []}
            classes.append(cur)
            pending = []
            i += 1
            continue
        s = line.strip()
        if cur is not None and s.startswith("##"):
            pending.append(s.lstrip("#").strip())
            i += 1
            continue
        m = re.match(r"^\s+const (\w+)\s*=\s*(.*)$", line)
        if cur is not None and m:
            name, rest = m.group(1), m.group(2)
            value, comment = rest, ""
            if "#" in rest and not rest.strip().startswith("{"):
                value, comment = rest.split("#", 1)
            value = value.strip()
            # Multi-line dictionaries and arrays.
            depth = value.count("{") + value.count("[") - value.count("}") - value.count("]")
            while depth > 0 and i + 1 < len(lines):
                i += 1
                nxt = lines[i].strip()
                value += " " + nxt
                depth += nxt.count("{") + nxt.count("[") - nxt.count("}") - nxt.count("]")
            value = re.sub(r"\s+", " ", value)
            note = comment.strip() or " ".join(pending)
            cur["consts"].append({"name": name, "value": value, "note": note})
            pending = []
            i += 1
            continue
        if s == "" or not s.startswith("#"):
            if s != "" and not s.startswith("const"):
                pending = []
        i += 1
    return classes


def code_files():
    out = []
    for d in CODE_DIRS:
        for base, _dirs, files in os.walk(os.path.join(ROOT, d)):
            for f in files:
                if not (f.endswith(".gd") or f.endswith(".cs")):
                    continue
                if f.startswith("test_"):
                    continue
                path = os.path.join(base, f)
                if os.path.abspath(path) == TUNING:
                    continue
                out.append(path)
    return sorted(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "tuning_catalogue.md"))
    args = ap.parse_args()
    with open(TUNING, encoding="utf-8") as fh:
        tuning_text = fh.read()
    classes = parse_tuning(tuning_text)
    sources = {}
    for path in code_files():
        with open(path, encoding="utf-8") as fh:
            sources[os.path.relpath(path, ROOT).replace(os.sep, "/")] = fh.read()
    parts = [INTRO]
    for cls in classes:
        if not cls["consts"]:
            continue
        parts.append("## %s\n\n| Constant | Value | Note | Used in |\n| --- | --- | --- | --- |\n" % cls["name"])
        for c in cls["consts"]:
            full = "Tuning.%s.%s" % (cls["name"], c["name"])
            alias = re.compile(r"\bconst %s\s*=\s*(?:C\.)?Tuning\.%s\.%s\b" % (c["name"], cls["name"], c["name"]))
            bare = re.compile(r"\b%s\b" % re.escape(c["name"]))
            content_alias = bool(alias.search(sources.get("sim/content.gd", "")))
            used = []
            for rel, text in sources.items():
                if full in text or (alias.search(text) and len(bare.findall(text)) > 1):
                    used.append(rel)
                elif content_alias and re.search(r"\bC\.%s\b" % re.escape(c["name"]), text):
                    used.append(rel)
            value = c["value"].replace("|", "\\|")
            if len(value) > 80:
                value = value[:77] + "..."
            note = c["note"].replace("|", "\\|")
            if used:
                where = ", ".join("`%s`" % u for u in sorted(set(used)))
            elif len(re.findall(r"\b%s\b" % re.escape(c["name"]), tuning_text)) > 1:
                where = "(only inside `sim/tuning.gd`)"
            else:
                where = "(unused)"
            parts.append("| `%s` | `%s` | %s | %s |\n" % (c["name"], value, note, where))
        parts.append("\n")
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write("".join(parts).rstrip() + "\n")
    print("wrote %s" % os.path.relpath(args.out, ROOT))


if __name__ == "__main__":
    main()
